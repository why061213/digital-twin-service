    /** 省内城市全连接 */
    private void buildIntraProvinceLinks() {
        for (List<String> cities : provinceToCities.values()) {
            for (int i = 0; i < cities.size(); i++) {
                for (int j = i + 1; j < cities.size(); j++) {
                    link(cities.get(i), cities.get(j), 1);
                }
            }
        }
    }

